"""Ingest findings from study labs (TryHackMe, LetsDefend, HTB) into the register.

The learning loop this closes is:

    study a room -> write a finding -> link it to a real risk -> record how the
    artefact changed -> publish the write-up

``labs/findings.sample.csv`` is the schema. Copy it to ``labs/findings.csv`` and
add one row per exercise. The command validates that every ``risk_id`` exists in
``data/risks.csv`` and that the platform URL is a real https link, then renders a
Markdown log that can be pasted into ``learning-log/``.

Nothing here is hardcoded: the severity/score context comes from the registry.
"""

from __future__ import annotations

import csv
from dataclasses import dataclass
from datetime import date
from pathlib import Path

from .registry import Registry
from .scales import level

FIELDS = [
    "finding_id",
    "date",
    "platform",
    "room",
    "room_url",
    "artifact",
    "risk_id",
    "severity",
    "summary",
    "resolution",
]

PLATFORMS = ("TryHackMe", "LetsDefend", "HackTheBox", "HTB Academy", "Other")
SEVERITIES = ("Baixo", "Moderado", "Alto", "Critico", "Crítico")


@dataclass(frozen=True)
class LabFinding:
    finding_id: str
    date: str
    platform: str
    room: str
    room_url: str
    artifact: str
    risk_id: str
    severity: str
    summary: str
    resolution: str


def load_lab_findings(path: str | Path) -> list[LabFinding]:
    source = Path(path)
    if not source.exists():
        raise FileNotFoundError(
            f"lab findings not found: {source} (copy labs/findings.sample.csv first)"
        )
    with source.open("r", encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        missing = [field for field in FIELDS if field not in (reader.fieldnames or [])]
        if missing:
            raise ValueError(f"{source}: missing column(s): {', '.join(missing)}")
        rows = list(reader)

    findings: list[LabFinding] = []
    for line, row in enumerate(rows, start=2):
        if None in row:
            raise ValueError(f"{source}:{line}: extra column(s)")
        values = {field: str(row.get(field, "")).strip() for field in FIELDS}
        if not values["finding_id"]:
            raise ValueError(f"{source}:{line}: finding_id is required")
        findings.append(LabFinding(**values))
    return findings


def validate_findings(findings: list[LabFinding], registry: Registry) -> list[str]:
    """Return data-quality issues, mirroring ``riskregister validate`` style."""

    risk_ids = {risk.id for risk in registry.risks}
    issues: list[str] = []
    seen: set[str] = set()

    for finding in findings:
        if finding.finding_id in seen:
            issues.append(f"{finding.finding_id}: duplicated finding_id")
        seen.add(finding.finding_id)
        if finding.risk_id not in risk_ids:
            issues.append(
                f"{finding.finding_id}: unknown risk {finding.risk_id!r} "
                "(add the risk to data/risks.csv first)"
            )
        if not finding.room_url.startswith("https://"):
            issues.append(f"{finding.finding_id}: room_url must start with https://")
        if finding.severity not in SEVERITIES:
            issues.append(
                f"{finding.finding_id}: severity {finding.severity!r} not in {SEVERITIES}"
            )
        try:
            date.fromisoformat(finding.date)
        except ValueError:
            issues.append(f"{finding.finding_id}: date must be YYYY-MM-DD")
        if not finding.summary:
            issues.append(f"{finding.finding_id}: summary is required")
        if not finding.resolution:
            issues.append(f"{finding.finding_id}: resolution is required")
    return issues


def _risk_context(registry: Registry, risk_id: str) -> str:
    for risk in registry.risks:
        if risk.id == risk_id:
            return (
                f"{risk.id} {risk.title} - residual {risk.residual_score} "
                f"({level(risk.residual_score)})"
            )
    return risk_id


def build_ingest_markdown(findings: list[LabFinding], registry: Registry) -> str:
    by_platform: dict[str, list[LabFinding]] = {}
    for finding in findings:
        by_platform.setdefault(finding.platform, []).append(finding)

    lines: list[str] = []
    add = lines.append
    add("# Lab Findings -> Risk Register")
    add("")
    add("> Generated by `python -m riskregister ingest`. Each row links a study "
        "exercise to a real risk and records how the repository changed.")
    add("")
    add("## 1) Summary")
    add("")
    add(f"- Findings ingested: **{len(findings)}**")
    add(f"- Platforms: **{len(by_platform)}** ({', '.join(sorted(by_platform))})")
    add(f"- Linked risks: **{len({f.risk_id for f in findings})}**")
    add("")
    add("## 2) Findings")
    add("")
    add("| ID | Date | Platform | Room | Risk | Severity | Artefact | How it was solved |")
    add("|---|---|---|---|---|---|---|---|")
    for finding in sorted(findings, key=lambda f: (f.date, f.finding_id)):
        add(
            f"| {finding.finding_id} | {finding.date} | {finding.platform} | "
            f"[{finding.room}]({finding.room_url}) | {finding.risk_id} | "
            f"{finding.severity} | {finding.artifact} | {finding.resolution} |"
        )
    add("")
    add("## 3) Per platform")
    add("")
    for platform in sorted(by_platform):
        add(f"### {platform}")
        add("")
        for finding in by_platform[platform]:
            add(f"- **{finding.finding_id}** ({finding.date}) - {finding.room}")
            add(f"  - Risk: {_risk_context(registry, finding.risk_id)}")
            add(f"  - Finding: {finding.summary}")
            add(f"  - Resolution: {finding.resolution}")
            add(f"  - Link: {finding.room_url}")
        add("")
    add("## 4) Reuse")
    add("")
    add("Paste these sections into `learning-log/YYYY-MM-DD-<room>.md` and commit the "
        "data row together with the code change it justified.")
    add("")
    return "\n".join(lines)
